import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';
const {outputText}=ts.transpileModule(await readFile('src/lib/cameraCapture.ts','utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}});
const {captureFrame,stopMotionTime,CAPTURE_SWAP_MS,CAPTURE_END_MS,ABOUT_REVEAL_MS}=await import('data:text/javascript;base64,'+Buffer.from(outputText).toString('base64'));
assert.equal(CAPTURE_SWAP_MS,560);assert.equal(CAPTURE_END_MS,2450);assert.equal(ABOUT_REVEAL_MS,1600);
for(let ms=500;ms<600;ms++)assert.equal(captureFrame(ms).flash,1);
assert.equal(captureFrame(499).flash,0);assert.equal(captureFrame(820).flash,0);
assert.equal(captureFrame(619).photoVisible,false);assert.equal(captureFrame(620).photoVisible,true);
const keys=['cameraY','x','y','z','pitch','roll','scale'];
for(let ms=1;ms<2450;ms++)if(stopMotionTime(ms)===stopMotionTime(ms-1))for(const key of keys)assert.equal(captureFrame(ms)[key],captureFrame(ms-1)[key]);
assert.equal(captureFrame(1200).pitch,0);assert.equal(captureFrame(1500).y,-4);assert.equal(captureFrame(1500).scale,1);
assert.ok(captureFrame(2407).y>105);assert.equal(captureFrame(2450).y,115);assert.equal(captureFrame(1800).cameraY,105);
console.log('PASS 83ms-quantized camera/photo transforms, opaque 500–600ms flash, covered page swap, ejection/hold, offscreen retirement before 2450ms');
