import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';
const {outputText}=ts.transpileModule(await readFile(new URL('../src/lib/backgroundRipples.ts',import.meta.url),'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}});
const {spawnRipple,advanceRipples,displaceRipple}=await import(`data:text/javascript;base64,${Buffer.from(outputText).toString('base64')}`);
const ripples=[];
for(let i=0;i<8;i++)spawnRipple(ripples,i,0,1280,720);
assert.equal(ripples.length,5);assert.equal(ripples[0].x,3);
const r={x:0,y:0,radius:200,maxRadius:1000,strength:48,bandWidth:160,alpha:1};
assert.deepEqual(displaceRipple(1000,1000,[r]),{x:1000,y:1000,highlight:0});
assert.ok(Math.abs(displaceRipple(240,0,[r]).x-240)>1);
assert.ok(displaceRipple(240,0,[r]).highlight>.3);
assert.deepEqual(displaceRipple(360,0,[r]),{x:360,y:0,highlight:0});
assert.ok(Object.values(displaceRipple(0,0,[{...r,radius:0}])).every(Number.isFinite));
const frames=[{...r}],halfFrames=[{...r}];advanceRipples(frames,1000/30);advanceRipples(halfFrames,1000/60);advanceRipples(halfFrames,1000/60);
assert.ok(Math.abs(frames[0].strength-halfFrames[0].strength)<1e-9);
for(let i=0;i<500;i++)advanceRipples(ripples,1000/60);
assert.equal(ripples.length,0);
console.log('PASS ripple cap, outside-band invariance, displacement, crest highlight, finite origin, frame-rate decay, expiry');
