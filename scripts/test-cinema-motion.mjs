import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';
const compile=s=>ts.transpileModule(s,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const url=s=>'data:text/javascript;base64,'+Buffer.from(s).toString('base64');
const bezelUrl=url(compile(await readFile('src/lib/bezelGeometry.ts','utf8')));
const source=compile(await readFile('src/lib/cinemaMotion.ts','utf8')).replace("'./bezelGeometry'",JSON.stringify(bezelUrl));
const {cinemaEase,cinemaClip,closeMix}=await import(url(source));
const {bezelGeometry}=await import(bezelUrl);
assert.equal(cinemaEase(0,true),0);assert.equal(cinemaEase(1,true),1);
for(let t=1;t<=550;t++)assert.ok(cinemaEase(t/550,true)>=cinemaEase((t-1)/550,true));
assert.deepEqual(closeMix(470),{backdrop:.06000000000000005,handoff:0});
assert.equal(closeMix(500).backdrop,0);assert.equal(closeMix(510).handoff,.5);assert.equal(closeMix(550).handoff,1);
const actual=cinemaClip(0,1200,700).match(/-?\d+(?:\.\d+)?(?:e[+-]?\d+)?/g).map(Number);
const curves=bezelGeometry(1000,600).curves;
const expected=[curves[0][0].x/1000,curves[0][0].y/600,...curves.flatMap(c=>c.slice(1).flatMap(p=>[p.x/1000,p.y/600]))];
assert.deepEqual(actual,expected,'closing silhouette must exactly match the live CRT path');
for(const p of [0,.25,.5,.75,1])assert.ok(!cinemaClip(p,600,360).includes('NaN'));
for(const hz of [60,120,240]){let samples=0;for(let ms=0;ms<550;ms+=1000/hz){const {handoff}=closeMix(ms);if(handoff>0&&handoff<1)samples++;}assert.ok(samples>=4);}
console.log('PASS exact CRT return curve, monotonic close, 500ms backdrop, continuous 80ms handoff at 60/120/240Hz');
